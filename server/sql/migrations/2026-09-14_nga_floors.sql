-- =====================================================================
-- 迁移：新增「每帖最多取几层（主楼+回复）」面板配置项
-- 日期：2026-09-14
-- 兼容：MySQL 8.0 / 5.7 / MariaDB（幂等，可重复执行）
--
-- 背景：实测发现同一页 HTML 里本来就有主楼 + 约 19 层回复（约 50KB），
--   但旧正则把结束标签写死成 </p>，而回复用的是 <span>，于是「抓回帖」从未生效
--   （一页 20 层只摘出 1 层）。修复后需要给运维一个可调旋钮：
--     1 层 = 只分析主楼；8 层 = 默认（提示词约 4259 tokens）；20 层 = 整页（约 9383 tokens）。
--   注意：取多少层**都不增加 HTTP 请求**，只增加送进 AI 的字数。
--
-- 说明：即使不跑本 SQL，后端启动时的 ensureDefaults() 也会按 SETTING_SCHEMA 补齐；
--       写在这里是为了改动可追溯，并给生产一个显式执行入口。
-- =====================================================================

INSERT IGNORE INTO system_settings (s_key, s_value, description) VALUES
  ('nga_content_max_floors', '8',
   '每帖最多取几层（主楼+回复）。同一页 HTML 里就有主楼+约19层回复，取回复不增加任何请求，只增加送进 AI 的字数：1层≈1248 tokens、8层≈4259、20层≈9383。实测 1层→8层 Gemini 时延只多 0.35 秒。填 1 = 只分析主楼');

/* ---------------- 校验 ---------------- */

SELECT s_key, s_value, LEFT(description, 60) AS description
  FROM system_settings
 WHERE s_key = 'nga_content_max_floors';
