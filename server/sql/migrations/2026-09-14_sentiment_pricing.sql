-- =====================================================================
-- 迁移：市场情绪参与撮合定价（新增 3 个配置项）
-- 日期：2026-09-14
-- 兼容：MySQL 8.0 / 5.7 / MariaDB（幂等，可重复执行）
--
-- 背景（用户需求）：
--   1) 市场情绪要与新闻因子一起影响股价；
--   2) 新增开关「是否在审核通过前影响撮合股价」——
--      审核的目的只是「不让 AI 输出未经审核就直接公开到网站」，
--      而不是「不让它影响价格」。
--
-- 定价公式（角色股）：涨跌幅 = clamp( (wP×压力 + wN×新闻 + wV×投票
--                                        + wS×市场情绪 + wI×基金传导) × 基础波动率, ±限幅 )
--   默认 wP=0.5 / wN=0.3 / wV=0.2 / wS=0.2 / wI=0.25（wI 面板可调）
-- 基金：情绪 = clamp( 压力 + (新闻×wN + 投票×wV + 舆情×wS) / wP )，再走原有溢价/收敛逻辑
--
-- 说明：这三项即使不跑本 SQL，后端启动时的 ensureDefaults() 也会按 SETTING_SCHEMA 补齐；
--       写在这里是为了改动可追溯，并给生产一个显式执行入口。
-- =====================================================================

INSERT IGNORE INTO system_settings (s_key, s_value, description) VALUES
  ('sentiment_before_review', '1',
   '开启（默认）：抓到的市场情绪与新闻一样直接参与撮合定价，审核只用于阻止未审文字公开到网站，不阻止它影响价格。关闭：必须管理员审核通过后才影响股价（与新闻同口径）'),
  ('sentiment_decay_hours', '72',
   '一条市场情绪影响股价的时长（小时，从抓取时刻起算）。超过不再计入定价。情绪更新频繁、衰减比新闻快，因此用小时而不是周期数'),
  ('sentiment_weight', '0.2',
   '情绪因子在定价公式里的权重。单周期价格影响 ≈ 权重 × 情绪因子(-1~1) × 基础波动率（0.2 满情绪约 ±0.4%）。设 0 = 情绪只展示不影响股价');

/* ---------------- 校验 ---------------- */

SELECT s_key, s_value, LEFT(description, 60) AS description
  FROM system_settings
 WHERE s_key IN ('sentiment_before_review', 'sentiment_decay_hours', 'sentiment_weight')
 ORDER BY s_key;
